// Writes config/donation_currencies.yml from a checked donation workbook.
// Refuses to write anything if the checker finds errors.
//
//   node export_yaml.js donation-config.xlsx
//   node export_yaml.js donation-config.xlsx --out some/other.yml

const fs = require( "node:fs" );
const path = require( "node:path" );
const yaml = require( "js-yaml" );
const {
  SETTINGS, DEFAULT_DONATION_URL, TIERS, FREQUENCIES
} = require( "./layout" );
const { checkWorkbook, report, parseCustomFields } = require( "./check" );
const { USD_RATES } = require( "./seed" );

const DEFAULT_OUT = path.join( __dirname, "..", "..", "config", "donation_currencies.yml" );

// Workbook frequency → YAML key, which is also FundraiseUp's recurring value
const FREQUENCY_KEYS = { "One-time": "once", Monthly: "monthly" };

// Formatting fields in the order they're written, with the values that can
// be left out of a currency because they're the default
const FORMAT_FIELDS = ["symbol", "format", "delimiter", "separator", "group_min_digits", "grouping"];
const FORMAT_DEFAULTS = { group_min_digits: 1, grouping: "standard" };

const HEADER = `# Donation amounts and currency formats for announcement shortcodes.
#
# Generated by tools/donation_config/export_yaml.js from the engagement
# workbook (WEB-1399). Edit the workbook, check it, and re-export; hand edits
# here are overwritten. tools/donation_config/FIELDS.md describes each field.
`;

const yesNo = value => {
  if ( value === "Yes" ) return true;
  if ( value === "No" ) return false;
  return undefined;
};

// Drops undefined values and empty objects, so optional keys are left out
function compact( object ) {
  const out = {};
  Object.entries( object ).forEach( ( [key, value] ) => {
    if ( value === undefined || value === null || value === "" ) return;
    if ( typeof value === "object" && !Array.isArray( value ) && Object.keys( value ).length === 0 ) return;
    out[key] = value;
  } );
  return out;
}

// { "One-time": { min: 5 }, Monthly: {} } as { once: { min: 5 } }
function tiersFor( amounts ) {
  return compact( Object.fromEntries( FREQUENCIES.map( freq => [
    FREQUENCY_KEYS[freq],
    compact( Object.fromEntries( TIERS.map( tier => [tier, amounts[freq]?.[tier]] ) ) )
  ] ) ) );
}

const withDefaults = fields => ( { ...FORMAT_DEFAULTS, ...fields } );

// All formatting fields, leaving out default values
function formatFields( fields ) {
  return compact( Object.fromEntries( FORMAT_FIELDS.map( key => [
    key, fields[key] === FORMAT_DEFAULTS[key] ? undefined : fields[key]
  ] ) ) );
}

// Only the formatting fields that differ from the level below
function formatDiff( fields, base ) {
  if ( !fields ) return {};
  const mine = withDefaults( fields );
  const theirs = withDefaults( base || {} );
  return compact( Object.fromEntries( FORMAT_FIELDS.map( key => [
    key, mine[key] === theirs[key] ? undefined : mine[key]
  ] ) ) );
}

// The YAML document as a plain object, from the checker's model
function buildConfig( { currencies, countries, countryLanguages, settings } ) {
  const defaultCountry = settings[SETTINGS.fallbackCountry];
  const usedCurrencies = new Set( Object.values( countries ).map( c => c.currency ) );

  const formatsByCountry = {};
  countryLanguages.forEach( ( { country, lang, fields } ) => {
    const diff = formatDiff( fields, countries[country].fields );
    if ( Object.keys( diff ).length === 0 ) return;
    formatsByCountry[country] = { ...formatsByCountry[country], [lang]: diff };
  } );

  const fru = compact( {
    default_url: settings[SETTINGS.defaultUrl] || DEFAULT_DONATION_URL,
    designation_id: settings[SETTINGS.designationId],
    custom_fields: settings[SETTINGS.customFields]
      ? parseCustomFields( settings[SETTINGS.customFields] )
      : undefined,
    utm_defaults: compact( {
      utm_source: settings[SETTINGS.utmSource],
      utm_medium: settings[SETTINGS.utmMedium]
    } )
  } );

  return compact( {
    default_country: defaultCountry,
    tier_names: TIERS,
    frequencies: Object.fromEntries( Object.values( FREQUENCY_KEYS ).map( k => [k, k] ) ),
    last_reviewed: settings[SETTINGS.lastReviewed],
    reviewed_by: settings[SETTINGS.reviewedBy],
    rates_updated: USD_RATES.updated,
    fru,
    currencies: Object.fromEntries( Object.keys( currencies ).sort( )
      .filter( code => usedCurrencies.has( code ) )
      .map( code => {
        const c = currencies[code];
        return [code, compact( {
          name: c.name,
          ...formatFields( c.fields ),
          tiers: tiersFor( c.amounts ),
          purchasing_power_adjusted: yesNo( c.purchasingPower ),
          fru_enabled: yesNo( c.fruEnabled ),
          fru_minimum: compact( Object.fromEntries( FREQUENCIES.map( freq => [
            FREQUENCY_KEYS[freq], c.fruMinimum[freq]
          ] ) ) )
        } )];
      } ) ),
    countries: Object.fromEntries( Object.keys( countries ).sort( ).map( code => {
      const c = countries[code];
      return [code, compact( {
        name: c.name,
        currency: c.currency,
        tiers: tiersFor( c.own ),
        ...formatDiff( c.ownFields, currencies[c.currency]?.fields ),
        formats: formatsByCountry[code],
        locales: c.langs.length > 0 ? c.langs : undefined,
        enabled: c.enabled ? undefined : false,
        notes: c.notes
      } )];
    } ) )
  } );
}

// js-yaml quotes keys like NO and ON that YAML 1.1 (Ruby's Psych) reads as
// booleans, but not other country codes. Quote them all, so hand-added ones
// are quoted by example.
function toYaml( config ) {
  const body = yaml.dump( config, {
    lineWidth: -1, noRefs: true, quotingType: "\"", forceQuotes: true
  } );
  return HEADER + body.replace( /^ {2}(?:"([A-Z]{2})"|([A-Z]{2})):/gm, ( _, quoted, bare ) => `  "${quoted || bare}":` );
}

async function exportYaml( input ) {
  const result = await checkWorkbook( input );
  if ( result.errors.length > 0 ) return { result, yaml: null };
  return { result, yaml: toYaml( buildConfig( result.model ) ) };
}

if ( require.main === module ) {
  const [input, flag, outArg] = process.argv.slice( 2 );
  if ( !input || ( flag && ( flag !== "--out" || !outArg ) ) ) {
    console.error( "Usage: node export_yaml.js <workbook.xlsx> [--out <file.yml>]" );
    process.exit( 2 );
  }
  const out = outArg || DEFAULT_OUT;
  exportYaml( input ).then( ( { result, yaml: text } ) => {
    if ( !text ) {
      console.log( report( result ) );
      console.error( "\nNot written: fix the errors above and export again." );
      process.exitCode = 1;
      return;
    }
    fs.writeFileSync( out, text );
    console.log( `Wrote ${out}` );
    if ( result.warnings.length > 0 ) {
      console.log( `${result.warnings.length} warnings; run check.js for the full report.` );
    }
  } );
}

module.exports = { buildConfig, toYaml, exportYaml };
